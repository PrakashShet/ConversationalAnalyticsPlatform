"""Unit tests for the HTML report exporter (no network/API needed)."""

from datetime import datetime, timezone

from app.core.report_export import build_report_html, export_report
from app.data.models import Analysis, ChartSpec, Kpi


def _sample() -> Analysis:
    return Analysis(
        question="How many orders in Mysore?",
        sql="SELECT count(*) FROM orders WHERE city='Mysore'",
        summary="There were 128 orders in Mysore.",
        kpis=[Kpi(label="Orders", value="128", delta="+12%", trend="up")],
        chart=ChartSpec(
            kind="bar",
            title="Orders by month",
            x=["Jul", "Aug", "Sep"],
            series=[{"name": "Orders", "data": [40, 45, 43]}],
        ),
        insights=["August was the peak month."],
        row_count=128,
        elapsed_ms=420,
        created_at=datetime(2026, 6, 7, tzinfo=timezone.utc),
    )


def test_build_report_html_contains_key_sections():
    html = build_report_html(_sample())
    assert "<!DOCTYPE html>" in html
    assert "How many orders in Mysore?" in html
    assert "128" in html
    assert "Orders by month" in html
    assert "August was the peak month." in html
    assert "Generated by Conv-Analytics" in html


def test_footer_does_not_name_a_model_version():
    """Model names go stale and the footer is not the place to track them.

    It previously claimed "Gemini 3.5 Flash", which is not a real model id.
    """
    html = build_report_html(_sample())

    assert "3.5 Flash" not in html
    assert "forecasts computed locally" in html


def test_export_report_writes_file(tmp_path):
    out = export_report(_sample(), tmp_path / "report.html")
    assert out.exists()
    assert out.read_text(encoding="utf-8").startswith("<!DOCTYPE html>")


def test_html_escaping_prevents_injection():
    a = _sample()
    a.summary = "<script>alert('x')</script>"
    html = build_report_html(a)
    assert "<script>alert('x')</script>" not in html
    assert "&lt;script&gt;" in html
